export const flagEmoji = (iso2) => {
  if (!iso2 || iso2.length !== 2) return '';
  const base = 0x1f1e6;
  return String.fromCodePoint(...[...iso2.toUpperCase()].map(c => base + c.charCodeAt(0) - 65));
};

